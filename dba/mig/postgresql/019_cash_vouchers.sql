-- DBA-owned receipt/payment voucher schema. A posted voucher is linked to its GL journal.
CREATE TABLE IF NOT EXISTS cash_vouchers (
    cash_voucher_id uuid PRIMARY KEY,
    company_id uuid NOT NULL REFERENCES companies(company_id),
    voucher_kind varchar(10) NOT NULL CHECK (voucher_kind IN ('RECEIPT','PAYMENT')),
    voucher_number varchar(100) NOT NULL CHECK (btrim(voucher_number) <> ''),
    voucher_date date NOT NULL,
    treasury_account_id uuid NOT NULL REFERENCES chart_of_accounts(account_id),
    party_name varchar(250),
    total_amount numeric(19,4) NOT NULL CHECK (total_amount > 0),
    currency_code char(3) NOT NULL CHECK (currency_code ~ '^[A-Z]{3}$'),
    exchange_rate numeric(19,8) NOT NULL CHECK (exchange_rate > 0),
    reference_number varchar(100),
    cost_center varchar(100),
    memo varchar(500),
    fiscal_period_id uuid NOT NULL REFERENCES fiscal_periods(fiscal_period_id),
    journal_entry_id uuid REFERENCES journal_entries(journal_entry_id),
    reversal_journal_entry_id uuid REFERENCES journal_entries(journal_entry_id),
    status smallint NOT NULL DEFAULT 0 CHECK (status IN (0,1,2)),
    created_by varchar(100) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    posted_by varchar(100),
    posted_at timestamptz,
    reversed_by varchar(100),
    reversed_at timestamptz,
    UNIQUE(company_id, voucher_kind, voucher_number)
);

CREATE TABLE IF NOT EXISTS cash_voucher_lines (
    cash_voucher_line_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cash_voucher_id uuid NOT NULL REFERENCES cash_vouchers(cash_voucher_id),
    line_number integer NOT NULL,
    account_id uuid NOT NULL REFERENCES chart_of_accounts(account_id),
    amount numeric(19,4) NOT NULL CHECK (amount > 0),
    cost_center varchar(100),
    invoice_reference varchar(100),
    note varchar(500),
    UNIQUE(cash_voucher_id, line_number)
);

CREATE TABLE IF NOT EXISTS cash_voucher_audit_events (
    cash_voucher_audit_event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cash_voucher_id uuid NOT NULL REFERENCES cash_vouchers(cash_voucher_id),
    event_type smallint NOT NULL CHECK (event_type IN (1,2,3)),
    actor varchar(100) NOT NULL,
    event_at timestamptz NOT NULL DEFAULT now(),
    details varchar(1000)
);

CREATE INDEX IF NOT EXISTS ix_cash_vouchers_company_date
    ON cash_vouchers(company_id, voucher_date, status);
CREATE INDEX IF NOT EXISTS ix_cash_voucher_lines_account
    ON cash_voucher_lines(account_id, cash_voucher_id);
CREATE INDEX IF NOT EXISTS ix_cash_voucher_audit_events_voucher
    ON cash_voucher_audit_events(cash_voucher_id, event_at);
