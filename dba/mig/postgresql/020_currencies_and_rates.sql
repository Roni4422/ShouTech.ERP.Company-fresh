-- Master currency definitions are shared reference data; exchange rates are company-scoped history.
CREATE TABLE IF NOT EXISTS currencies (
    currency_code char(3) PRIMARY KEY CHECK (currency_code ~ '^[A-Z]{3}$'),
    currency_name_ar varchar(100) NOT NULL CHECK (btrim(currency_name_ar) <> ''),
    currency_name_en varchar(100),
    symbol varchar(10),
    fraction_name varchar(100),
    decimal_places smallint NOT NULL DEFAULT 2 CHECK (decimal_places BETWEEN 0 AND 6),
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS currency_rates (
    rate_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id uuid NOT NULL REFERENCES companies(company_id),
    from_currency char(3) NOT NULL REFERENCES currencies(currency_code),
    to_currency char(3) NOT NULL REFERENCES currencies(currency_code),
    rate numeric(19,8) NOT NULL CHECK (rate > 0),
    buy_rate numeric(19,8) NOT NULL CHECK (buy_rate > 0),
    sell_rate numeric(19,8) NOT NULL CHECK (sell_rate > 0),
    min_rate numeric(19,8) NOT NULL CHECK (min_rate > 0),
    max_rate numeric(19,8) NOT NULL CHECK (max_rate > 0),
    effective_date date NOT NULL,
    notes varchar(500),
    created_by varchar(100) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_currency_rates_company_pair_date
        UNIQUE(company_id, from_currency, to_currency, effective_date),
    CHECK (min_rate <= rate AND rate <= max_rate),
    CHECK (buy_rate <= sell_rate)
);

CREATE TABLE IF NOT EXISTS currency_audit_events (
    currency_audit_event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    currency_code char(3) NOT NULL REFERENCES currencies(currency_code),
    event_type varchar(20) NOT NULL CHECK (event_type IN ('CREATED','UPDATED','RATE_ADDED')),
    actor varchar(100) NOT NULL,
    event_at timestamptz NOT NULL DEFAULT now(),
    details varchar(1000)
);

CREATE INDEX IF NOT EXISTS ix_currency_rates_lookup
    ON currency_rates(company_id, from_currency, to_currency, effective_date DESC);
CREATE INDEX IF NOT EXISTS ix_currency_audit_events_code
    ON currency_audit_events(currency_code, event_at DESC);

